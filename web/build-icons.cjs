'use strict';
// Regenerate with: node web/build-icons.cjs /path/to/lucide@1.8.0
// A pristine dist/umd/lucide.min.js is also accepted. Only regeneration needs
// the upstream package; production and the normal test suite need no dependency.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const vm = require('node:vm');

const SOURCE_SHA256 = 'ab85225ecc1daa2033607856f03dd2dabcbc08e2d260a5b97e17c690aa929766';
// Include dynamic project actions/types/tabs and model status/key-visibility icons.
const ICONS = Object.freeze([
  'arrow-left', 'arrow-up', 'check', 'chevron-down', 'chevron-right',
  'circle-alert', 'circle-check', 'code-2', 'download', 'ellipsis', 'eye', 'eye-off',
  'file', 'file-check-2', 'file-search', 'file-text', 'flag', 'folder-open', 'globe', 'info',
  'list-collapse', 'loader-circle', 'locate-fixed', 'maximize', 'maximize-2',
  'message-square-plus', 'minus', 'notebook-text', 'paperclip', 'pause', 'play', 'plug',
  'plus', 'rotate-ccw', 'search', 'settings-2', 'shield-check', 'sliders-horizontal',
  'square', 'trash-2', 'workflow', 'x'
]);
const exportName = name => name.replace(/(^|-)(\w)/g, (_, separator, letter) => letter.toUpperCase());

function sourceFile(input) {
  const resolved = path.resolve(input);
  if (!fs.statSync(resolved).isDirectory()) return resolved;
  const manifest = JSON.parse(fs.readFileSync(path.join(resolved, 'package.json'), 'utf8'));
  if (manifest.name !== 'lucide' || manifest.version !== '1.8.0') throw new Error('Requires lucide@1.8.0');
  return path.join(resolved, 'dist/umd/lucide.min.js');
}

function buildSubset(source) {
  if (crypto.createHash('sha256').update(source).digest('hex') !== SOURCE_SHA256) {
    throw new Error('Upstream Lucide checksum mismatch; use the pristine lucide@1.8.0 UMD bundle');
  }
  const text = source.toString('utf8');
  const uniqueIndex = anchor => {
    const index = text.indexOf(anchor);
    if (index < 0 || text.indexOf(anchor, index + 1) !== -1) throw new Error('Unexpected Lucide boundary: ' + anchor);
    return index;
  };
  const glyphStart = uniqueIndex(',za=[[');
  const rendererStart = uniqueIndex('const Uu=');
  const exportStart = uniqueIndex(';a.AArrowDown=');
  if (!(glyphStart < rendererStart && rendererStart < exportStart)) throw new Error('Unexpected Lucide layout');
  const upstream = {};
  vm.runInNewContext(text, {exports: upstream, module: {exports: upstream}}, {timeout: 1000});
  if (Object.keys(upstream.icons).length !== 1939 || Object.keys(upstream).length !== 1942) {
    throw new Error('Unexpected Lucide exports');
  }
  const glyphs = ICONS.map(name => {
    const key = exportName(name), glyph = upstream.icons[key];
    if (!Array.isArray(glyph) || glyph.length === 0) throw new Error('Unknown Lucide icon: ' + name);
    return key + ':' + JSON.stringify(glyph);
  }).join(',');
  // Keep the official helpers and createIcons renderer byte-for-byte. Replace
  // only glyph declarations, the default icon table, and unused named exports.
  return '// Generated by web/build-icons.cjs; license: THIRD-PARTY-NOTICES.txt\n' +
    text.slice(0, glyphStart) + ';const Tu=Object.freeze({__proto__:null,' + glyphs + '});' +
    text.slice(rendererStart, exportStart) +
    ';Object.assign(a,Tu),a.createElement=ka,a.createIcons=Uu,a.icons=Tu}));\n';
}

if (require.main === module) {
  if (process.argv.length !== 3) throw new Error('Usage: node web/build-icons.cjs <lucide@1.8.0 package directory or pristine UMD file>');
  const bundle = buildSubset(fs.readFileSync(sourceFile(process.argv[2])));
  fs.writeFileSync(path.join(__dirname, 'static/lucide.min.js'), bundle);
  console.log(`Bundled ${ICONS.length} Lucide icons: ${Buffer.byteLength(bundle)} bytes`);
}

module.exports = {ICONS, SOURCE_SHA256, exportName, sourceFile, buildSubset};
